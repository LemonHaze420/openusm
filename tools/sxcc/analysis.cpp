function_analysis_t analyze_function(const function_t &function)
{
    function_analysis_t result;
    const auto &code = function.code;
    if (code.empty()) {
        result.diagnostics.push_back("Empty executable function");
        return result;
    }
    std::map<unsigned, unsigned> instruction_at;
    std::vector<unsigned> offsets;
    unsigned offset = 0;
    for (unsigned i = 0; i < code.size(); ++i) {
        instruction_at.emplace(offset, i);
        offsets.push_back(offset);
        if (code[i].size() > UINT32_MAX - offset) {
            result.diagnostics.push_back("Function size overflow");
            return result;
        }
        offset += code[i].size();
    }
    std::set<unsigned> leaders{0};
    for (unsigned i = 0; i < code.size(); ++i) {
        const auto &instruction = code[i];
        if (is_branch(instruction.opcode)) {
            auto target = static_cast<std::int64_t>(offsets[i]) + instruction.size() +
                          static_cast<std::int16_t>(instruction.value);
            if (target < 0 || target >= offset ||
                instruction_at.find(static_cast<unsigned>(target)) == instruction_at.end()) {
                result.diagnostics.push_back("Branch at " + hex(offsets[i]) +
                                             " does not target a function instruction");
                return result;
            }
            leaders.insert(instruction_at.at(static_cast<unsigned>(target)));
        }
        if (is_branch(instruction.opcode) || instruction.opcode == OP_RET || instruction.opcode == OP_KIL ||
            instruction.opcode == OP_DEL_THREADS) {
            if (i + 1 < code.size())
                leaders.insert(i + 1);
        }
    }
    for (auto begin : leaders) {
        result.block_at.emplace(begin, static_cast<unsigned>(result.blocks.size()));
        result.blocks.push_back({begin, static_cast<unsigned>(code.size()), {}, {}});
    }
    for (unsigned i = 0; i + 1 < result.blocks.size(); ++i)
        result.blocks[i].end = result.blocks[i + 1].begin;
    for (unsigned i = 0; i < result.blocks.size(); ++i) {
        auto &block = result.blocks[i];
        const auto &last = code[block.end - 1];
        if (is_branch(last.opcode)) {
            auto target =
                static_cast<std::int64_t>(offsets[block.end - 1]) + last.size() + static_cast<std::int16_t>(last.value);
            block.successors.push_back(result.block_at.at(instruction_at.at(static_cast<unsigned>(target))));
        }
        bool terminates = last.opcode == OP_RET || last.opcode == OP_BRA ||
                          ((last.opcode == OP_KIL || last.opcode == OP_DEL_THREADS) && last.argument == OP_ARG_NULL);
        if (!terminates) {
            if (i + 1 < result.blocks.size())
                block.successors.push_back(i + 1);
            else
                result.diagnostics.push_back("Function can fall through its bytecode boundary");
        }
        std::sort(block.successors.begin(), block.successors.end());
        block.successors.erase(std::unique(block.successors.begin(), block.successors.end()), block.successors.end());
    }
    for (unsigned i = 0; i < result.blocks.size(); ++i)
        for (auto successor : result.blocks[i].successors)
            result.blocks[successor].predecessors.push_back(i);
    return result;
}

symbols_t load_symbols(const std::string &dictionary)
{
    symbols_t symbols;
    symbols.type_sizes.emplace("signal", 4);
    for (const auto &variable : native_variables)
        symbols.variables.emplace(variable.name, std::make_pair(variable.game, variable.offset));
    for (unsigned i = 0; i < std::size(native_classes); ++i) {
        const auto &type = native_classes[i];
        symbols.type_sizes.emplace(type.name, type.size);
        symbols.class_ids.emplace(type.name, i);
        symbols.type_evidence.emplace(type.name, type.registration);
        if (*type.parent)
            symbols.parents.emplace(type.name, type.parent);
    }
    for (const auto &record : native_functions) {
        native_t native;
        native.class_id = record.class_id;
        native.function_id = record.function_id;
        native.class_name = native_classes[record.class_id].name;
        native.signature = record.signature;
        native.implementation = record.implementation;
        if (record.result_size >= 0)
            native.result_bytes = static_cast<unsigned>(record.result_size);
        if (*record.result_type)
            native.result = record.result_type;
        auto opening = native.signature.find('(');
        auto function_name = native.signature.substr(0, opening);
        if (record.class_id != 0 && function_name != native.class_name)
            native.parameters.push_back(native.class_name);
        auto parameters = std::string_view(native.signature).substr(opening + 1);
        parameters.remove_suffix(1);
        while (!parameters.empty()) {
            auto comma = parameters.find(',');
            auto parameter = parameters.substr(0, comma);
            if (parameter == "...")
                native.variadic = true;
            else
                native.parameters.emplace_back(parameter);
            if (comma == std::string_view::npos)
                break;
            parameters.remove_prefix(comma + 1);
        }
        for (const auto &parameter : native.parameters)
            native.parameter_bytes += symbols.type_sizes.at(parameter);
        if (function_name == native.class_name && native.result_bytes == symbols.type_sizes.at(native.class_name))
            native.result = native.class_name;
        symbols.natives.emplace(std::make_pair(native.class_id, native.function_id), std::move(native));
    }
    if (dictionary.empty())
        return symbols;
    std::ifstream file(dictionary);
    if (!file)
        throw error_t("Cannot open symbol dictionary " + dictionary);
    std::string line;
    while (std::getline(file, line)) {
        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        if (!line.starts_with("0x"))
            continue;
        auto tab = line.find('\t');
        if (tab == std::string::npos)
            throw error_t("Malformed hash dictionary line");
        std::uint32_t value = 0;
        auto parsed = std::from_chars(line.data() + 2, line.data() + tab, value, 16);
        if (parsed.ec != std::errc{} || parsed.ptr != line.data() + tab)
            throw error_t("Malformed dictionary hash");
        auto name = line.substr(tab + 1);
        if (name_hash(name) != value)
            throw error_t("Dictionary hash does not match its string: " + name);
        auto [it, inserted] = symbols.names.emplace(value, name);
        if (!inserted && it->second != name)
            throw error_t("Ambiguous dictionary hash " + hex(value));
    }
    return symbols;
}

void resolve_symbols(image_t &image, const symbols_t &symbols)
{
    auto name_for = [&](std::uint32_t hash, std::string &name) {
        auto found = symbols.names.find(hash);
        if (found != symbols.names.end())
            name = found->second;
    };
    for (auto &object : image.objects) {
        name_for(object.name_hash, object.name);
        for (auto &function : object.functions)
            name_for(function.fullname_hash, function.name);
    }
    for (auto &initializer : image.initializers)
        if (initializer.builder)
            name_for(initializer.builder->fullname_hash, initializer.builder->name);
}

